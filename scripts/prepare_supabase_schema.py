"""Prepare PostgreSQL DDL from a verified SQLite backup, without cloud writes.

The generated DDL targets a private schema and includes no personal data.
This is preparation only: review and test on PostgreSQL before applying.
"""
import argparse
import json
import re
import sqlite3
from pathlib import Path

from backup_before_supabase import digest, quote


def split_definitions(sql):
    """Split a CREATE TABLE body, respecting nested expressions and literals."""
    body = sql[sql.index('(') + 1:sql.rindex(')')]
    parts, start, depth, quoted, i = [], 0, 0, None, 0
    while i < len(body):
        char = body[i]
        if quoted:
            if char == quoted:
                if i + 1 < len(body) and body[i + 1] == quoted:
                    i += 1
                else:
                    quoted = None
        elif char in "'\"`":
            quoted = char
        elif char == '(':
            depth += 1
        elif char == ')':
            depth -= 1
        elif char == ',' and depth == 0:
            parts.append(body[start:i].strip())
            start = i + 1
        i += 1
    parts.append(body[start:].strip())
    return parts


def convert_table(db, name, ddl):
    info = db.execute('PRAGMA table_info(' + quote(name) + ')').fetchall()
    metadata = {row[1]: row for row in info}
    definitions, identities = [], []
    for part in split_definitions(ddl):
        if re.match(r'FOREIGN\s+KEY\b', part, re.I):
            continue  # Added separately, after every table exists.
        if re.match(r'(?:CONSTRAINT|PRIMARY\s+KEY|UNIQUE|CHECK)\b', part, re.I):
            definitions.append(part)
            continue
        match = re.match(r'("[^"]+"|`[^`]+`|\w+)\s+(.*)', part, re.S)
        if not match:
            raise ValueError('Unsupported column definition in ' + name)
        column, rest = match.group(1).strip('"`'), match.group(2)
        declared = metadata[column][2].upper()
        if declared not in {'INTEGER', 'TEXT', 'TIMESTAMP', 'REAL', 'BLOB'}:
            raise ValueError('Unsupported SQLite type: ' + declared)
        # All current inline references occur at the end of the definition.
        rest = re.sub(r'\s+REFERENCES\b.*$', '', rest, flags=re.I | re.S)
        rest = re.sub(r'\bAUTOINCREMENT\b', '', rest, flags=re.I)
        pg_type = {'INTEGER': 'BIGINT', 'TEXT': 'TEXT', 'TIMESTAMP': 'TIMESTAMP',
                   'REAL': 'DOUBLE PRECISION', 'BLOB': 'BYTEA'}[declared]
        rest = re.sub(r'^' + declared + r'\b', pg_type, rest, count=1, flags=re.I)
        if column == 'id' and metadata[column][5] == 1 and declared == 'INTEGER':
            rest = re.sub(r'^BIGINT\b', 'BIGINT GENERATED BY DEFAULT AS IDENTITY', rest)
            identities.append(column)
        if declared == 'TEXT':
            rest = re.sub(r'\bDEFAULT\s+CURRENT_TIMESTAMP\b',
                          "DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))",
                          rest, flags=re.I)
        definitions.append(quote(column) + ' ' + rest.strip())
    return 'CREATE TABLE ' + quote(name) + ' (\n    ' + ',\n    '.join(definitions) + '\n);', identities


def prepare(backup, output):
    manifest = json.loads((backup / 'manifest.json').read_text(encoding='utf-8'))
    if manifest.get('status') != 'verified' or digest(backup / 'database.db') != manifest['database_sha256']:
        raise ValueError('Expected an unchanged, verified backup')
    output.mkdir(parents=True, exist_ok=False)
    statements = ['-- PREPARATION ONLY. Review/test before use. No records included.',
                  'BEGIN;', 'CREATE SCHEMA talentsouk;',
                  'REVOKE ALL ON SCHEMA talentsouk FROM PUBLIC;',
                  'SET LOCAL search_path TO talentsouk;',
                  "SET LOCAL TIME ZONE 'UTC';"]
    identities, foreign_keys = {}, []
    with sqlite3.connect((backup / 'database.db').resolve().as_uri() + '?mode=ro', uri=True) as db:
        tables = db.execute("SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").fetchall()
        for name, ddl in tables:
            converted, ids = convert_table(db, name, ddl)
            identities[name] = ids
            statements.append(converted)
        for name, _ in tables:
            groups = {}
            for row in db.execute('PRAGMA foreign_key_list(' + quote(name) + ')'):
                groups.setdefault(row[0], []).append(row)
            for number, rows in groups.items():
                rows.sort(key=lambda row: row[1])
                parent = rows[0][2]
                target_columns = [row[4] for row in rows]
                if any(value is None for value in target_columns):
                    target_columns = [r[1] for r in sorted(db.execute('PRAGMA table_info(' + quote(parent) + ')'), key=lambda r: r[5]) if r[5]]
                constraint = name + '_fk_' + str(number)
                statement = ('ALTER TABLE ' + quote(name) + ' ADD CONSTRAINT ' + quote(constraint)
                             + ' FOREIGN KEY (' + ','.join(quote(r[3]) for r in rows) + ') REFERENCES '
                             + quote(parent) + ' (' + ','.join(map(quote, target_columns)) + ')'
                             + ' ON UPDATE ' + rows[0][5] + ' ON DELETE ' + rows[0][6] + ';')
                foreign_keys.append({'table': name, 'name': constraint, 'sql': statement})
        statements.extend(item['sql'] for item in foreign_keys)
        for name, sql in db.execute("SELECT name,sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL ORDER BY name"):
            statements.append(sql.rstrip(';') + ';')
        triggers = [row[0] for row in db.execute("SELECT name FROM sqlite_master WHERE type='trigger'")]
        if set(triggers) - {'queue_notification_mail'}:
            raise ValueError('An unhandled trigger requires review')
        if 'queue_notification_mail' in triggers:
            statements.extend([
                "CREATE FUNCTION queue_notification_mail_fn() RETURNS trigger LANGUAGE plpgsql SET search_path = talentsouk AS $$ BEGIN INSERT INTO notification_mail_queue(notification_id,user_id) VALUES(NEW.id,NEW.user_id); RETURN NEW; END; $$;",
                'CREATE TRIGGER queue_notification_mail AFTER INSERT ON notifications FOR EACH ROW EXECUTE FUNCTION queue_notification_mail_fn();'
            ])
        # No browser access to the app tables; Flask will use a server connection.
        for name, _ in tables:
            statements.append('ALTER TABLE ' + quote(name) + ' ENABLE ROW LEVEL SECURITY;')
        statements.append('COMMIT;')
    (output / 'schema.postgres.sql').write_text('\n\n'.join(statements) + '\n', encoding='utf-8')
    readiness = {
        'stage': 'prepared_not_applied', 'source_backup': str(backup.resolve()),
        'tables': len(tables), 'rows': sum(t['rows'] for t in manifest['tables'].values()),
        'identities': identities, 'foreign_keys': foreign_keys,
        'blocking_foreign_key_issues': manifest['foreign_key_issues'],
        'import_allowed': True,
        'historical_constraints_require_validation': bool(manifest['foreign_key_issues']),
        'notes': [
            'The importer preserves historical orphan rows and marks only their foreign keys NOT VALID. New writes enforce these relationships. No source records are modified.',
            'Create schema in a fresh staging project. CREATE SCHEMA fails if the schema already exists; nothing is dropped.',
            'Import must preserve IDs, disable only the notification queue trigger while copying, reset identity sequences, and compare all records before commit.',
            'SQLite UNIQUE constraints allow multiple NULL values. Verify composite primary keys for NULL data before import.',
            'This schema does not migrate Flask SQL, account authentication to Supabase Auth, or upload files to Storage.',
            'No PostgreSQL connection was available; generated DDL still requires database execution tests.'
        ]
    }
    (output / 'readiness.json').write_text(json.dumps(readiness, ensure_ascii=False, indent=2), encoding='utf-8')
    print(json.dumps({'output': str(output.resolve()), 'tables': len(tables), 'foreign_keys': len(foreign_keys), 'import_allowed': readiness['import_allowed']}))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--backup', required=True, type=Path)
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    prepare(args.backup, args.output)
