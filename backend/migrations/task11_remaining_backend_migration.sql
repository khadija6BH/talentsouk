-- Idempotent migration for the two remaining backend blockers.
create extension if not exists unaccent;

alter table public.jobs add column if not exists company_id bigint;

do $$
begin
    if not exists (
        select 1 from pg_constraint
        where conname = 'jobs_company_id_fkey'
          and conrelid = 'public.jobs'::regclass
    ) then
        alter table public.jobs
            add constraint jobs_company_id_fkey
            foreign key (company_id) references public.companies(id)
            on update cascade on delete set null;
    end if;
end $$;

create index if not exists jobs_company_id_idx on public.jobs(company_id);

with unique_companies as (
    select min(id) as id,
           trim(regexp_replace(lower(unaccent(name)), '[^a-z0-9]+', ' ', 'g')) as normalized_name
    from public.companies
    where nullif(trim(name), '') is not null
    group by trim(regexp_replace(lower(unaccent(name)), '[^a-z0-9]+', ' ', 'g'))
    having count(*) = 1
)
update public.jobs as job
set company_id = company.id
from unique_companies as company
where job.company_id is null
  and nullif(trim(job.company_name), '') is not null
  and trim(regexp_replace(lower(unaccent(job.company_name)), '[^a-z0-9]+', ' ', 'g')) = company.normalized_name;

create table if not exists public.crm (
    id bigint generated by default as identity primary key,
    company_id bigint not null references public.companies(id)
        on update cascade on delete cascade,
    contact_email text,
    status text not null default 'Target',
    last_contact_date date,
    next_followup_date date,
    notes text not null default '',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists crm_company_id_idx on public.crm(company_id);
create index if not exists crm_status_idx on public.crm(status);

alter table public.crm enable row level security;

do $$
begin
    if not exists (
        select 1 from pg_policies
        where schemaname = 'public' and tablename = 'crm'
          and policyname = 'Backend service access'
    ) then
        create policy "Backend service access" on public.crm
            for all to service_role using (true) with check (true);
    end if;
end $$;

select
    count(*) filter (where company_id is not null) as linked_jobs,
    count(*) filter (where company_id is null) as unmatched_jobs
from public.jobs;
